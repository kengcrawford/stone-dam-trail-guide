// Extracts the tour content from public/index.html so the Ask function
// answers from exactly what visitors see. Runs on every Netlify build.
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const html = readFileSync(new URL("../public/index.html", import.meta.url), "utf8");
function grab(name) {
  const start = html.indexOf(`const ${name} = [`);
  if (start < 0) throw new Error(`Could not find ${name} in index.html`);
  const end = html.indexOf("\n];", start);
  return html.slice(start, end + 3);
}
const ctx = {};
vm.createContext(ctx);
vm.runInContext(`${grab("NATURE")}\n${grab("STOPS")}\nthis.NATURE = NATURE; this.STOPS = STOPS;`, ctx);

const stops = ctx.STOPS.map(s => [
  `STOP ${s.id}: ${s.title} (${s.short})`,
  `Story: ${s.story.join(" ")}`,
  `What a visitor sees: ${s.describe}`,
  `Pause and notice: ${s.notice}`,
  `Access (sample values, not yet measured): distance ${s.dist}; surface ${s.surface}; slope ${s.grade}; bench ${s.bench}; restroom ${s.restroom}; sound ${s.sound}; ${s.stepfree ? "on the step-free route" : "NOT step-free (gravel/grass)"}.`
].join("\n")).join("\n\n");

const species = ctx.NATURE.map(n => [
  `${n.name} (${n.sci}) — ${n.cat}${n.caution ? " — CAUTION: do not touch" : ""}`,
  `${n.blurb} Look for: ${n.look} Other senses: ${n.sense} Why it matters: ${n.why}`,
  `Near stops ${n.stops.join(", ")}; seasons: ${n.seasons.join(", ")}.`
].join("\n")).join("\n\n");

const GUIDE = `PARK: Allen Station Park, along Cottonwood Creek, Allen, Texas. The guide covers a walk of about 0.7 mile one way past the 1874 Old Stone Dam (Allen Water Station, National Register of Historic Places; State Archaeological Landmark).

ROUTES: Full creek walk (7 stops, about 0.7 mi one way, 45–60 min, one gravel stop). Short and level (stops 1–4, 0.3 mi one way, all paved, benches at stops 1, 3 and 4). From home (all stories, no walking). Accessible parking and restroom at the trailhead (Stop 1).

STOPS
${stops}

FIELD GUIDE
${species}

SAFETY: Stay on the trail. Most snakes are harmless but copperheads live in North Texas leaf litter. Watch for poison ivy and fire ant mounds. Give wildlife room, never feed animals, keep dogs leashed. Leave plants, nuts and stones in place.`;

const out = new URL("../netlify/lib/guide.mjs", import.meta.url);
writeFileSync(out, `// Generated by scripts/build-guide.mjs. Do not edit by hand.\nexport const GUIDE = ${JSON.stringify(GUIDE)};\n`);
console.log(`guide.mjs written: ${GUIDE.length} characters, ${ctx.STOPS.length} stops, ${ctx.NATURE.length} species`);
